package waypoint.p4;

import waypoint.Bed;
import waypoint.Checker;
import waypoint.Model;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.*;

/**
 * P4: S1/S2 cancellation-boundary matrix on the calibration bed.
 *
 * For each cancel point K in {3,10,17,30}: record a stream whose length is
 * exactly K chunks and that is cancelled at K ({@code Bed.doGen()} writes K
 * chunks then {@code CANCELLED(K)}), inject deterministic crashes at every
 * operation boundary, resume, and evaluate S1:
 *   - recorded chunk count == K (log self-consistency),
 *   - configured K == the K recorded in the log (config/log cross-check),
 *   - replay emissions == K (via {@code Bed.replayStream()}: replays the
 *     durable prefix without calling the model and without writing the log),
 *   - no post-cancel model call.
 * S2 (compaction provenance) is asserted on the same runs.
 *
 * Scope: this matrix is a regression and sensitivity test over the calibration
 * bed, not independent evidence about real frameworks. A sensitivity section
 * injects known S1 violations (M9, M12) and requires them to be detected;
 * otherwise the matrix proves nothing and the gate fails.
 *
 * Output: build/s1-matrix.md (untracked, regenerated by ./p4/gate.sh).
 */
public final class CancelBoundaryMatrix {

    public static void main(String[] args) throws Exception {
        StringBuilder out = new StringBuilder();
        out.append("# P4: S1/S2 cancellation-boundary matrix\n\n");
        out.append("生成：`./p4/gate.sh`（每次运行重算；产物 `build/s1-matrix.md`，不写入版本库）。\n");
        out.append("流长度 = K：`Bed.doGen()` 恰写 K 个 chunk 后写 `CANCELLED(K)`；不存在「30-chunk 流」。\n\n");
        out.append("| cancelAt | crash-runs | S1-active | S1 violations | S2 violations | other findings |\n");
        out.append("|---|---|---|---|---|---|\n");

        boolean matrixClean = true;
        int totalRuns = 0, totalActive = 0, totalActiveCrash = 0;
        for (int cancelAt : new int[]{3, 10, 17, 30}) {
            Bed.Config base = base(cancelAt);
            long ops = opsFor(base);
            int runs = 0, active = 0, activeCrash = 0, s1 = 0, s2 = 0, other = 0;
            for (long k = -1; k <= ops; k++) {
                Bed.Config c = base.copy();
                c.crashAtOp = k;
                Checker.RunResult rr = runOnce(c, "S1m/K" + cancelAt + "@k" + k);
                if (hasCancelled(rr.events)) {
                    active++;
                    if (k >= 1) activeCrash++; // k=-1 and k=0 are no-crash control runs
                }
                for (Checker.Finding f : Checker.check(rr)) {
                    if (f.contract.equals("S1")) s1++;
                    else if (f.contract.equals("S2")) s2++;
                    else other++;
                }
                runs++;
            }
            matrixClean &= (s1 == 0 && s2 == 0 && other == 0);
            totalRuns += runs;
            totalActive += active;
            totalActiveCrash += activeCrash;
            out.append("| ").append(cancelAt).append(" | ").append(runs).append(" | ").append(active)
               .append(" | ").append(s1).append(" | ").append(s2).append(" | ").append(other).append(" |\n");
        }
        out.append("\nS1-active = 恢复后日志中存在 CANCELLED 的 run（边界断言可执行）；无 CANCELLED 的 run 不适用该断言。");
        out.append("合计 ").append(totalRuns).append(" runs / S1-active ").append(totalActive)
           .append("（其中真实崩溃 run ").append(totalActiveCrash).append("；无崩溃对照 ")
           .append(totalActive - totalActiveCrash).append("）。\n");
        out.append("S1 violations 覆盖：日志 chunk 数 != K、配置 K != 日志 K、`replayStream()` 发射数 != K、取消后重复 gen。\n");

        // ---- sensitivity: the matrix must not be vacuous ----
        Sens s1M9 = sensitivityS1(true, false);
        Sens s1M12 = sensitivityS1(false, true);
        boolean sensM9 = s1M9.s1() > 0;
        boolean sensM12 = s1M12.s1() > 0;

        out.append("\n## 灵敏度（注入已知 S1 违例，必须被捕获）\n\n");
        out.append("| 注入 | 机制 | runs | S1 violations | 期望 |\n|---|---|---|---|---|\n");
        out.append("| M9 | cancel-boundary-overrun（日志多记 1 chunk） | ").append(s1M9.runs())
           .append(" | ").append(s1M9.s1()).append(" | >0 |\n");
        out.append("| M12 | replay-emits-wrong-chunks（replayStream 发射数错误） | ").append(s1M12.runs())
           .append(" | ").append(s1M12.s1()).append(" | >0 |\n");

        boolean pass = matrixClean && sensM9 && sensM12;
        out.append("\n## 口径与限制\n\n");
        out.append("- 本矩阵是校准床上的回归/灵敏度测试，不是对真实框架 S1 语义的独立证据。\n");
        out.append("- S2 在本矩阵中没有可失败路径（只有 M10 注入会让重放重调 `summarize`），因此「S2 0 违例」不作为 S2 成立的独立证据。\n");
        out.append("- S3 不在本矩阵断言（p4 只主张 S1/S2）：中途崩溃后恢复会合法地重调 `summarize`，把 `meteringPre/FinalEntries` 接通会产生假阳性。\n");
        out.append("- replay 断言使用 `Bed.replayStream()`（不调用模型、不写日志）；`preAppliedCounts` 取恢复前快照（C1 前置条件可成立）。\n");
        out.append("\ngate: ").append(pass ? "PASS" : "FAIL")
           .append(": matrix-0-violations=").append(matrixClean)
           .append("; sensitivity-M9=").append(sensM9)
           .append("; sensitivity-M12=").append(sensM12).append("\n");

        String report = out.toString();
        System.out.print(report);
        Files.createDirectories(Path.of("build"));
        Files.writeString(Path.of("build/s1-matrix.md"), report);
        System.exit(pass ? 0 : 1);
    }

    static Bed.Config base(int cancelAt) {
        Bed.Config base = Bed.Config.healthy(Bed.Workflow.W2_STREAM);
        base.cancelAt = cancelAt;
        return base;
    }

    static boolean hasCancelled(List<Model.Event> events) {
        for (Model.Event e : events) if (e.type == Model.Type.CANCELLED) return true;
        return false;
    }

    /** Full sweep with one injected S1 violation. */
    record Sens(int runs, int s1) {}

    static Sens sensitivityS1(boolean m9, boolean m12) {
        Bed.Config cfg = base(17);
        if (m9) cfg.m9OverrunCancel = true;
        if (m12) cfg.m12ReplayEmitsWrongChunks = true;
        long ops = opsFor(cfg);
        int runs = 0, s1 = 0;
        for (long k = -1; k <= ops; k++) {
            Bed.Config c = cfg.copy();
            c.crashAtOp = k;
            Checker.RunResult rr = runOnce(c, "S1m/sensitivity@k" + k);
            for (Checker.Finding f : Checker.check(rr)) if (f.contract.equals("S1")) s1++;
            runs++;
        }
        return new Sens(runs, s1);
    }

    static long opsFor(Bed.Config cfg) {
        Bed bed = new Bed(cfg, new waypoint.WaypointLog.MemoryDisk(), new Model.ExternalLedger(), new Model.ModelSpy());
        bed.recordRun();
        return bed.opsExecuted();
    }

    static Checker.RunResult runOnce(Bed.Config cfg, String name) {
        waypoint.WaypointLog.MemoryDisk disk = new waypoint.WaypointLog.MemoryDisk();
        Model.ExternalLedger ext = new Model.ExternalLedger();
        Model.ModelSpy model = new Model.ModelSpy();
        Model.MeteringLedger metering = new Model.MeteringLedger();
        Bed bed = new Bed(cfg, disk, ext, model, metering);
        try { bed.recordRun(); } catch (Bed.Crash ignored) { }
        List<Model.Event> pre = parse(disk);
        Map<String, String> keyByPath = new HashMap<>();
        Set<String> preCompleted = new HashSet<>();
        for (Model.Event e : pre) if (e.type == Model.Type.STEP_STARTED) keyByPath.put(e.f1, e.f2);
        for (Model.Event e : pre) if (e.type == Model.Type.STEP_COMPLETED) {
            String k = keyByPath.get(e.f1);
            if (k != null) preCompleted.add(k);
        }
        int preSummarize = model.count("summarize", "root/compact");
        boolean preCompaction = false;
        for (Model.Event e : pre) if (e.type == Model.Type.COMPACTION) preCompaction = true;
        // C1 requires a pre-recovery snapshot (a post-recovery snapshot makes the
        // "final > pre" condition structurally impossible).
        Map<String, Integer> preApplied = ext.appliedCounts();

        Bed.Config rc = cfg.copy(); rc.crashAtOp = -1;
        Bed bed2 = new Bed(rc, disk, ext, model, metering);
        Bed.RecoverOutcome o = bed2.recover(Bed.RecoverMode.FULL);
        // S1 replay assertion: replay the durable prefix (no model call, no log write).
        int replayEmitted = new Bed(rc, disk, ext, model, metering).replayStream();
        // preMetering and metering.size() are not propagated as
        // meteringPre/PostEntries; see the S3 note below.

        Checker.RunResult rr = new Checker.RunResult();
        rr.scenario = name;
        rr.events = parse(disk);
        rr.ext = ext; rr.model = model;
        rr.preCompletedKeys = Set.copyOf(preCompleted);
        rr.preAppliedCounts = preApplied;
        rr.expectedSteps = Bed.expectedSteps(cfg.workflow); // activates C1 skip half
        rr.cancelAt = cfg.cancelAt;
        rr.preCompactionDurable = preCompaction;
        rr.preSummarizeCalls = preSummarize;
        if (hasCancelled(rr.events)) {
            rr.configuredCancelAt = cfg.cancelAt;
            rr.replayChunksEmitted = replayEmitted;
        }
        // S3 is NOT asserted by this matrix: S3 needs a replay-scoped metering
        // observation, and after a mid-generation crash the recovery path
        // legitimately re-runs compaction (a real model call, not a replay).
        // Letting meteringPre/Post default (0/0) keeps S3 inactive instead of
        // producing a false "replay produced new metering entries".
        rr.stateHash = Model.stateHash(o.finalStatus(), o.chunkCounts());
        return rr;
    }

    static List<Model.Event> parse(waypoint.WaypointLog.MemoryDisk disk) {
        List<Model.Event> out = new ArrayList<>();
        for (byte[] raw : new waypoint.WaypointLog.Wal(disk).durableParsed()) out.add(Model.Event.decode(raw));
        return out;
    }
}
